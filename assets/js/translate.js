async function loadTranslations(lang) {
  try {
    // // Fetch the translation file
    // const response = await fetch(`translations/${lang}.json`);
    // const translations = await response.json();

    // Update elements with translations
    document.querySelectorAll('[data-translate]').forEach(el => {
      const key = el.getAttribute('data-translate');

      // Define data attributes we want to check for
      const dataAttributes = [
        'description',
        'title',
        'aircraft-reg',
        'price',
        'range',
        'speed',
        'night-rated',
        'avionics',
        'default'
      ];

      // Check for translations with data attributes first
      dataAttributes.forEach(attr => {
        const attrKey = `${key}_${attr}`;
        if (translations[lang][attrKey]) {
          console.log(attrKey)
          el.setAttribute(`data-${attr}`, translations[lang][attrKey]);
        }
      });

      // Then check for direct translation without attributes
      if (translations[lang][key] && !el.hasAttribute('keep-text')) {
        el.innerHTML = translations[lang][key];
      }
    });
  } catch (error) {
    console.error('Error loading translations:', error);
  }
}

// Example: Change language to Czech
document.addEventListener('DOMContentLoaded', () => {
  const userLang = navigator.language.startsWith('cs') ? 'cs' : 'en'; // Auto-detect user language
  loadTranslations('cs');

  // // Example button to switch languages manually
  document.getElementById('switch-lang-en').addEventListener('click', () => loadTranslations('en'));
  document.getElementById('switch-lang-cs').addEventListener('click', () => loadTranslations('cs'));
});
